-- InviteIZI: таблицы бота и заказов.
-- Доступ: только роль сервера inviteizi_server (Next.js через пулер). anon/authenticated — ничего.

-- ── updated_at ──
create or replace function public.set_updated_at()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

-- ── Пользователи Telegram ──
create table public.users (
  id            bigint primary key,                       -- Telegram user id
  username      text,
  first_name    text,
  lang          text check (lang in ('uz', 'ru')),        -- null — ещё не выбрал
  step          text not null default 'start',
  state         jsonb not null default '{}'::jsonb,
  source        text,                                     -- ?start=insta / qr_…
  created_at    timestamptz not null default now(),
  last_seen_at  timestamptz not null default now()
);

-- ── Админы (кроме ADMIN_IDS из env) ──
create table public.admins (
  telegram_id  bigint primary key,
  name         text,
  created_at   timestamptz not null default now()
);

-- ── Дизайны (сид из templates/registry.ts: scripts/seed-templates.mjs) ──
create table public.templates (
  id          text primary key,
  number      int not null unique,
  occasion    text not null check (occasion in ('nikoh', 'sunnat', 'nahorgi', 'yubiley')),
  format      text not null check (format in ('animated', 'simple')),
  with_photo  boolean not null default false,
  price       int not null check (price >= 0),
  cover_url   text,
  is_active   boolean not null default true,
  sort        int not null default 0
);

-- ── Наш список музыки ──
create table public.music (
  id                text primary key,
  title_uz          text not null,
  title_ru          text not null,
  file_url          text not null,
  telegram_file_id  text,
  sort              int not null default 0,
  is_active         boolean not null default true
);

-- ── Заказы ──
create table public.orders (
  id                   uuid primary key default gen_random_uuid(),
  number               int generated by default as identity (start with 101) unique,
  user_id              bigint not null references public.users (id) on delete cascade,
  status               text not null default 'preview'
                         check (status in ('draft', 'preview', 'awaiting_payment', 'receipt_sent', 'active', 'archived', 'rejected')),
  occasion             text not null check (occasion in ('nikoh', 'sunnat', 'nahorgi', 'yubiley')),
  format               text not null check (format in ('animated', 'simple')),
  template_id          text not null references public.templates (id) on update cascade,
  -- данные пригласительного (InvitationData)
  relation             text check (relation in ('farzand', 'ogil', 'qiz', 'nabira', 'uka', 'ona', 'ota', 'ozimiz')),
  groom                text,
  bride                text,
  person               text,
  cause                text check (cause in ('nikoh', 'sunnat', 'yubiley')),
  age                  int check (age between 0 and 150),
  hosts                text not null default '',
  side_groom           text,
  side_bride           text,
  text_id              text,
  custom_text          text check (char_length(custom_text) <= 600),
  -- музыка
  music_kind           text not null default 'none' check (music_kind in ('list', 'own', 'none')),
  music_id             text references public.music (id) on update cascade,
  music_file_id        text,
  music_url            text,
  music_title          text,
  -- ссылка и оплата
  slug                 text not null unique
                         check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$' and char_length(slug) <= 60
                                -- заняты страницами сайта (lib/slug.ts RESERVED_SLUGS)
                                and slug not in ('demo', 'catalog', 'api', 'admin', 'art', 'covers', 'music', 'pilots', 'previews')),
  amount               int not null check (amount >= 0),
  receipt_file_id      text,
  receipt_kind         text check (receipt_kind in ('photo', 'document')),
  reject_reason        text,
  created_at           timestamptz not null default now(),
  updated_at           timestamptz not null default now(),
  receipt_at           timestamptz,
  paid_at              timestamptz,
  payment_reminded_at  timestamptz,
  admin_reminded_at    timestamptz,
  expires_at           timestamptz,
  constraint orders_music_list_has_id check (music_kind <> 'list' or music_id is not null),
  constraint orders_music_own_has_file check (music_kind <> 'own' or music_file_id is not null),
  constraint orders_receipt_pair check ((receipt_file_id is null) = (receipt_kind is null))
);

create trigger orders_set_updated_at
  before update on public.orders
  for each row execute function public.set_updated_at();

create index orders_user_id_idx on public.orders (user_id, created_at desc);
create index orders_status_idx on public.orders (status, created_at);
create index orders_template_id_idx on public.orders (template_id);
create index orders_music_id_idx on public.orders (music_id) where music_id is not null;

-- ── Тадбиры заказа (1–3) ──
create table public.events (
  id          bigint generated always as identity primary key,
  order_id    uuid not null references public.orders (id) on delete cascade,
  position    smallint not null check (position between 0 and 2),
  kind        text not null check (kind in ('nahorgi', 'nikohMarosim', 'nikohBazm', 'kelinSalom', 'sunnatBazm', 'yubileyBazm')),
  date        date not null,
  time        text not null check (time ~ '^([01][0-9]|2[0-3]):[0-5][0-9]$'),
  venue_name  text not null default '',
  address     text not null default '',
  lat         double precision check (lat between -90 and 90),
  lng         double precision check (lng between -180 and 180),
  map_url     text,
  unique (order_id, position),
  constraint events_latlng_pair check ((lat is null) = (lng is null))
);

-- ── Доступ ──
-- Supabase по умолчанию даёт anon/authenticated права на новые таблицы в public — забираем.
revoke all on public.users, public.admins, public.templates, public.music, public.orders, public.events
  from anon, authenticated;

alter table public.users     enable row level security;
alter table public.admins    enable row level security;
alter table public.templates enable row level security;
alter table public.music     enable row level security;
alter table public.orders    enable row level security;
alter table public.events    enable row level security;

grant usage on schema public to inviteizi_server;
grant select, insert, update, delete
  on public.users, public.admins, public.templates, public.music, public.orders, public.events
  to inviteizi_server;
grant usage, select on all sequences in schema public to inviteizi_server;

create policy server_all on public.users     for all to inviteizi_server using (true) with check (true);
create policy server_all on public.admins    for all to inviteizi_server using (true) with check (true);
create policy server_all on public.templates for all to inviteizi_server using (true) with check (true);
create policy server_all on public.music     for all to inviteizi_server using (true) with check (true);
create policy server_all on public.orders    for all to inviteizi_server using (true) with check (true);
create policy server_all on public.events    for all to inviteizi_server using (true) with check (true);
